function wrap(g, text, maxW) {
  const out = []; let line = '';
  for (const w of text.split(' ')) { const t = line ? line + ' ' + w : w; if (g.measureText(t).width > maxW && line) { out.push(line); line = w; } else line = t; }
  if (line) out.push(line); return out;
}
function text(g, s, x, y, px, wt = 500, col = PAL.text, o = {}) {
  g.save(); g.font = font(px, wt, o.fam || 'ui'); g.fillStyle = col; g.textBaseline = o.base || 'alphabetic'; g.textAlign = o.align || 'left';
  if (o.alpha != null) g.globalAlpha *= o.alpha; g.fillText(s, x, y); g.restore();
}
const typed = (s, t, t0, cps = 16) => s.slice(0, clamp(Math.floor((t - t0) * cps), 0, s.length));
// UI-expand transition: a section opens from a small pill at its focal point (no fades, no blank frames)
function expandClip(g, t, t0, cx = W / 2, cy = H / 2) {
  const p = back(seg(t, t0 - 0.04, t0 + 0.42), 1.3);
  if (p >= 1) return false;
  const w = lerp(160, W + 40, p), h = lerp(56, H + 40, p);
  g.save(); rr(g, cx - w / 2 + (W / 2 - cx) * p, cy - h / 2 + (H / 2 - cy) * p, w, h, lerp(28, 0, p)); g.clip(); return true;
}
// Section header: "TRUCO 0N" label + one-line title snapping in
function header(g, t, t0, n, title) {
  g.save(); g.setTransform(1, 0, 0, 1, 0, 0);   // titles are screen-space: camera moves never crop them
  const p = seg(t, t0 + 0.3, t0 + 0.75), q = back(p, 1.3);
  text(g, `TRUCO 0${n}`, 120, 150 - (1 - q) * 14, 22, 600, PAL.accent, { fam: 'mono', alpha: p });
  text(g, title, 120, 222 - (1 - q) * 24, 64, 600, PAL.text, { alpha: p });
  // progress dots: which trick of 7
  for (let i = 0; i < 7; i++) {
    const on = i < n, cur = i === n - 1;
    g.save(); g.fillStyle = cur ? PAL.accent : on ? 'rgba(139,124,255,.45)' : 'rgba(255,255,255,.12)';
    if (cur) { g.shadowColor = rgba(PAL.accent, 0.8); g.shadowBlur = 12; }
    rr(g, W - 120 - (7 - i) * 34, 136, 22, 8, 4); g.fill(); g.restore();
  }
  g.restore();
}
function stage(g, cam, o = {}) {
  E.bg(g, o); E.grid(g, { ox: W / 2 - cam.x * cam.zoom, oy: H / 2 - cam.y * cam.zoom, scale: cam.zoom });
}
// Grey "wall of text" lines (the problem image), generated by rule
function wallLines(g, x, y, w, n, t0, t, o = {}) {
  const { rate = 9, alpha = 1, tremble = 0 } = o;
  for (let i = 0; i < n; i++) {
    const ti = t0 + i / rate; if (t < ti) break;
    const p = eo(seg(t, ti, ti + 0.2)), lw = w * (0.55 + hash(i * 3.7) * 0.45) * (i % 6 === 5 ? 0.5 : 1);
    const dx = tremble * (hash(Math.floor(t * 24) + i) - 0.5) * 4;
    g.fillStyle = `rgba(160,168,184,${0.22 * alpha * p})`; rr(g, x + dx, y + i * 22 + (1 - p) * 6, lw, 9, 4.5); g.fill();
  }
}
function bubble(g, x, y, w, h, o = {}) {
  const { me = false, accent = false, alpha = 1 } = o;
  g.save(); g.globalAlpha *= alpha;
  if (accent) { g.shadowColor = rgba(PAL.accent, 0.5); g.shadowBlur = 30; }
  g.fillStyle = me ? 'rgba(139,124,255,.22)' : accent ? '#1C1A30' : PAL.surf2; rr(g, x, y, w, h, 22); g.fill(); g.shadowColor = 'transparent';
  g.strokeStyle = accent ? rgba(PAL.accent, 0.9) : 'rgba(255,255,255,.09)'; g.lineWidth = accent ? 2 : 1; rr(g, x + 0.5, y + 0.5, w - 1, h - 1, 22); g.stroke();
  g.restore();
}
function chip(g, s, x, y, o = {}) {
  const { accent = false, red = false, px = 26, alpha = 1, mono = false, center = false } = o;
  g.save(); g.globalAlpha *= alpha; g.font = font(px, 600, mono ? 'mono' : 'ui');
  const w = g.measureText(s).width + px * 1.4, h = px * 1.9, xx = center ? x - w / 2 : x;
  const c = red ? PAL.red : accent ? PAL.accent : null;
  if (c) { g.shadowColor = rgba(c, 0.6); g.shadowBlur = 18; }
  g.fillStyle = c ? rgba(c, 0.16) : 'rgba(255,255,255,.06)'; rr(g, xx, y, w, h, h / 2); g.fill(); g.shadowColor = 'transparent';
  g.strokeStyle = c ? rgba(c, 0.85) : 'rgba(255,255,255,.14)'; g.lineWidth = 1.5; rr(g, xx + 0.5, y + 0.5, w - 1, h - 1, h / 2); g.stroke();
  g.fillStyle = c || PAL.text; g.textBaseline = 'middle'; g.fillText(s, xx + px * 0.7, y + h / 2 + 1);
  g.restore(); return w;
}
const pop = (t, t0) => back(seg(t, t0, t0 + 0.26), 1.3);

// ───────── the chat window, shared by the opening and the echo ─────────
const CW = { x: 460, y: 150, w: 1000, h: 700 };
function chatFrame(g, t, prompt, typeT0) {
  const r = E.windowBox(g, CW.x, CW.y, CW.w, CW.h, { title: 'Asistente', app: 3 });
  // input row
  const iy = CW.y + CW.h - 84;
  g.fillStyle = 'rgba(255,255,255,.05)'; rr(g, CW.x + 24, iy, CW.w - 48, 60, 30); g.fill();
  g.strokeStyle = 'rgba(255,255,255,.1)'; g.lineWidth = 1; rr(g, CW.x + 24.5, iy + 0.5, CW.w - 49, 59, 30); g.stroke();
  const shown = typed(prompt, t, typeT0, 14), sent = t > typeT0 + prompt.length / 14 + 0.35;
  g.font = font(26, 500);
  const tx = CW.x + 56, tw = sent ? 0 : g.measureText(shown).width;
  if (!sent) text(g, shown || '', tx, iy + 39, 26, 500, PAL.text);
  E.caret(g, tx + tw + 6, iy + 30, 30, { on: (sent || Math.floor(t * 2) % 2 === 0 || t < typeT0 + prompt.length / 14) ? 1 : 0.2 });
  return { r, sent, sendT: typeT0 + prompt.length / 14 + 0.35 };
}
function promptBubble(g, t, t0, prompt) {
  const p = pop(t, t0); if (p <= 0) return;
  g.font = font(26, 500); const w = g.measureText(prompt).width + 48;
  g.save(); g.translate(CW.x + CW.w - 40 - w, CW.y + 76 + (1 - p) * 30);
  bubble(g, 0, 0, w, 56, { me: true, alpha: clamp(p) }); text(g, prompt, 24, 37, 26, 500, PAL.text, { alpha: clamp(p) }); g.restore();
}

