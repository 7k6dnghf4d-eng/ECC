const PROMPT = 'hazme un plan para ahorrar';
function sceneHook(g, t) {
  // 0–3 s: pull back from the caret (locked extreme close-up → window); 10–20 s: the wall overflows, dutch angle; 20–31: it breaks
  const z = lerp(3.2, 1, eio(seg(t, 0.2, 3.0)));
  const rot = 0.025 * ss(seg(t, 11, 16)) * (1 - ss(seg(t, 19.5, 20.5)));
  const cam = E.camera({ x: lerp(CW.x + 70, W / 2, eio(seg(t, 0.2, 3.0))), y: lerp(CW.y + CW.h - 54, H / 2, eio(seg(t, 0.2, 3.0))), zoom: z, rot });
  E.bg(g); cam.apply(g); E.grid(g, { rect: [-2000, -2000, 6000, 6000] });
  const { sent, sendT } = chatFrame(g, t, PROMPT, 0.6);
  if (sent) promptBubble(g, t, sendT, PROMPT);
  // the answer: a wall, growing past the window
  const brk = seg(t, 20, 22.5);
  const wx = CW.x + 40, wy = CW.y + 160;
  g.save(); rr(g, CW.x, CW.y + 140, CW.w, CW.h - 240, 0); g.clip();
  if (brk <= 0) wallLines(g, wx, wy - Math.max(0, (t - 7) * 26), 760, 120, sendT + 0.5, t, { rate: 7, tremble: seg(t, 11, 14) * (1 - seg(t, 19, 20)) });
  g.restore();
  // red badges: the problem colour exists only while the problem does
  const badges = [['1.247 palabras', 9.2, 1180, 330], ['genérico', 11.0, 1230, 470], ['¿y mi caso?', 12.6, 1150, 610]];
  for (const [s, t0, bx, by] of badges) { const p = pop(t, t0) * (1 - seg(t, 20, 20.4)); if (p > 0) { g.save(); g.translate(bx, by); g.scale(p, p); chip(g, s, 0, 0, { red: true, px: 24 }); g.restore(); } }
  // break: wall lines fly apart (generated pieces), then title
  if (brk > 0 && t < 26) {
    for (let i = 0; i < 40; i++) {
      const a = hash(i * 7.1) * TAU, d = eo(brk) * (500 + hash(i) * 900), x = wx + hash(i * 2.3) * 700, y = wy + (i % 20) * 22;
      g.save(); g.globalAlpha = 1 - brk; g.translate(x + Math.cos(a) * d, y + Math.sin(a) * d + brk * brk * 300); g.rotate((hash(i * 5) - 0.5) * brk * 3);
      g.fillStyle = 'rgba(160,168,184,.3)'; rr(g, -60, -5, 120, 10, 5); g.fill(); g.restore();
    }
  }
  g.setTransform(1, 0, 0, 1, 0, 0);
  // 22.5–31: the thesis, one line per screen, then the promise
  if (t > 22.3) {
    const p1 = seg(t, 22.4, 22.8), p2 = seg(t, 26.2, 26.6);
    g.save(); g.fillStyle = `rgba(8,9,12,${0.82 * eo(p1)})`; g.fillRect(0, 0, W, H); g.restore();
    if (t < 26.2) text(g, 'El problema no es la IA.', W / 2, 520 + (1 - back(p1, 1.3)) * 20, 72, 600, PAL.text, { align: 'center', alpha: p1 });
    else {
      E.scramble(g, '7', W / 2 - 210, 590, t, [26.6], { px: 260, color: PAL.accent, align: 'center' });
      text(g, 'trucos', W / 2 - 110, 560, 96, 600, PAL.text, { alpha: p2 });
      text(g, 'para que la IA te responda bien', W / 2 - 110, 620, 32, 500, PAL.dim, { alpha: seg(t, 27, 27.4) });
    }
  }
}

